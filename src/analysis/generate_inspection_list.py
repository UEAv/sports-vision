"""
Stage 3 - Manual Inspection Timestamp Generator

Uses the combined event tables already generated by the annotation-analysis
scripts to pick one real example timestamp per event type, so you can jump
straight to it in the video instead of scrubbing blindly.

Usage:
    python src/analysis/generate_inspection_list.py
"""

from pathlib import Path
import pandas as pd
import sys

sys.path.append(str(Path(__file__).resolve().parents[2]))
from src.utils.logger import get_logger

logger = get_logger(__name__)

ROOTS_RISE_EVENTS = Path("data/analysis/all_events_combined.csv")
OUTPUT = Path("data/analysis/manual_inspection_list.csv")


def ms_to_mmss(ms: float) -> str:
    total_seconds = int(ms / 1000)
    minutes, seconds = divmod(total_seconds, 60)
    return f"{minutes:02d}:{seconds:02d}"


def main():
    if not ROOTS_RISE_EVENTS.exists():
        logger.error(f"{ROOTS_RISE_EVENTS} not found - run analyze_annotations.py first.")
        return

    df = pd.read_csv(ROOTS_RISE_EVENTS)

    # Map source_file (JSON name) to its matching video file
    video_map = {
        "634821e2a66446a7bd99493205dc93": "data/roots_rise/634821e2a66446a7bd99493205dc93.mp4",
        "71378fbd4d6541859bb9f2b95c1473": "data/roots_rise/71378fbd4d6541859bb9f2b95c1473.mp4",
        "b4fd089bdd614687a43458bd340fc8": "data/roots_rise/b4fd089bdd614687a43458bd340fc8.mp4",
    }

    # Pick ONE example event per type (the first occurrence is fine for a spot-check)
    examples = df.groupby("type").first().reset_index()

    rows = []
    for _, row in examples.iterrows():
        game_id = row["game_id_from_file"]
        video_path = video_map.get(game_id, "UNKNOWN - check source_file manually")
        timestamp_mmss = ms_to_mmss(row["video_time"])
        rows.append({
            "event_type": row["type"],
            "video_file": video_path,
            "timestamp_ms": row["video_time"],
            "timestamp_mmss": timestamp_mmss,
            "team": row.get("team", "N/A"),
            "checked": "NO",
            "zoom_level": "",
            "ball_visibility": "",
            "occlusion": "",
            "notes": "",
        })

    result_df = pd.DataFrame(rows)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    result_df.to_csv(OUTPUT, index=False)

    print("\n=== MANUAL INSPECTION LIST ===")
    print("One example per event type found in Roots & Rise IQ data.\n")
    for _, row in result_df.iterrows():
        print(f"  [{row['event_type']:20s}] {row['video_file']}  @ {row['timestamp_mmss']}  (team: {row['team']})")

    print(f"\nSaved editable checklist to: {OUTPUT.resolve()}")
    print("Open this CSV in Excel and fill in zoom_level / ball_visibility / occlusion / notes as you watch each one.")
    print("\nTIP: most video players let you jump to a timestamp directly, or use VLC's")
    print("'Jump to specific time' (Ctrl+T) to go straight to the MM:SS shown above.")


if __name__ == "__main__":
    main()
